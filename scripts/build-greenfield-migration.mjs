import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const output = resolve(
  root,
  "supabase/greenfield/00000000000000_perkcommons_fork.sql",
);
const sources = [
  "supabase/migrations/202607170001_moderation_system.sql",
  "supabase/migrations/202607170002_moderation_retention.sql",
  "supabase/migrations/202607170003_submission_website_compatibility.sql",
  "supabase/migrations/202607180001_opportunity_taxonomy.sql",
  "supabase/migrations/202607190001_moderation_workspace.sql",
  "supabase/migrations/202607190002_automated_publication.sql",
  "supabase/migrations/202607190003_automated_listing_removal.sql",
  "supabase/migrations/202607220001_next_review_concurrency.sql",
  "supabase/migrations/202607220002_publication_semantics.sql",
  "supabase/migrations/202607240001_listing_update_workflow.sql",
];

const stripTransaction = (sql) =>
  sql
    .split(/\r?\n/)
    .filter((line) => !/^\s*(begin|commit);\s*$/i.test(line))
    .join("\n")
    .replaceAll("set search_path = public", "set search_path = ''")
    .trim();

const prelude = `-- PerkCommons Next fork: greenfield Supabase baseline
-- Generated by scripts/build-greenfield-migration.mjs.
--
-- EMPTY PROJECTS ONLY. Do not apply this file after the incremental migrations.
-- It creates private submission/moderation state. It does not create users,
-- credentials, storage buckets, Cloudflare resources, or GitHub integrations.

begin;

do $preflight$
begin
  if to_regclass('auth.users') is null then
    raise exception 'PerkCommons baseline requires a Supabase project with auth.users';
  end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role')
     or not exists (select 1 from pg_roles where rolname = 'authenticated')
     or not exists (select 1 from pg_roles where rolname = 'anon') then
    raise exception 'PerkCommons baseline requires Supabase API roles';
  end if;
  if to_regclass('public.opportunity_submissions') is not null then
    raise exception 'PerkCommons greenfield baseline requires an empty public application schema';
  end if;
end
$preflight$;

create extension if not exists pgcrypto;

create table public.opportunity_submissions (
  id uuid primary key default gen_random_uuid(),
  organization text not null,
  name text not null,
  categories text[] not null default '{}',
  source_url text not null,
  website_url text not null,
  description text not null,
  eligibility text not null,
  location text,
  deadline date,
  submitter_name text,
  submitter_email text,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);`;

const postlude = `-- Final greenfield-only hardening and compatibility.
drop trigger if exists opportunity_submissions_touch_updated_at
  on public.opportunity_submissions;
create trigger opportunity_submissions_touch_updated_at
before update on public.opportunity_submissions
for each row execute function public.touch_updated_at();

grant usage on schema public to service_role;
grant all privileges on all tables in schema public to service_role;
grant all privileges on all sequences in schema public to service_role;

-- Browser roles receive no direct access to private workflow tables. Public
-- intake and moderator operations go through the fork Worker with service-role
-- isolation and explicit RPC grants.
revoke all privileges on all tables in schema public from anon, authenticated;
revoke all privileges on all sequences in schema public from anon, authenticated;

commit;
`;

const sections = [];
for (const source of sources) {
  const absolute = resolve(root, source);
  sections.push(
    `-- --------------------------------------------------------------------------\n` +
      `-- Squashed from ${relative(root, absolute)}\n` +
      `-- --------------------------------------------------------------------------\n` +
      stripTransaction(await readFile(absolute, "utf8")),
  );
}

const generated = `${prelude}\n\n${sections.join("\n\n")}\n\n${postlude}`;
if (check) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(
      `${relative(root, output)} is stale. Run node scripts/build-greenfield-migration.mjs.`,
    );
    process.exitCode = 1;
  } else {
    console.log(`${relative(root, output)} is current.`);
  }
  process.exit();
}
await mkdir(dirname(output), { recursive: true });
await writeFile(output, generated, "utf8");
console.log(`Generated ${relative(root, output)} from ${sources.length} migrations.`);
