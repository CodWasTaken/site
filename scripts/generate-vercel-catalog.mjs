import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = {
  "/data/opportunities.json": "dist/data/opportunities.json",
  "/provider-index.json": "dist/provider-index.json",
  "/facet-counts.json": "dist/facet-counts.json",
};

const catalogAssets = {};
for (const [publicPath, relativePath] of Object.entries(sources)) {
  const raw = await readFile(join(root, relativePath), "utf8");
  catalogAssets[publicPath] = JSON.parse(raw);
}

const outputPath = join(root, "vercel/generated-catalog.mjs");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/generate-vercel-catalog.mjs. Do not edit.\nexport const catalogAssets = ${JSON.stringify(catalogAssets)};\n`,
);
console.log(
  `Generated Vercel catalogue module with ${Object.keys(catalogAssets).length} public assets.`,
);
